#!/bin/bash
# Generates docs/reference/shell/ from shdoc annotations under shell/. Never
# hand-edit the output — see docs/architecture/docs-system.md.

set -eu

out_dir=docs/reference/shell
rm -rf "${out_dir}"
mkdir -p "${out_dir}"
# shellcheck disable=SC2016 # literal backticks in printf output, not interpolation
printf '# Shell reference\n\nGenerated by `mise run docs` from shdoc annotations under `shell/`.\n\n' >"${out_dir}/index.md"

for f in $(find shell -name '*.sh' | sort); do
  rel="${f#shell/}"
  out="${out_dir}/${rel%.sh}.md"
  mkdir -p "$(dirname "$out")"
  gawk -f scripts/shdoc <"$f" >"$out"
  # shellcheck disable=SC2016 # literal backtick in printf output, not interpolation
  printf -- '- [`%s`](%s)\n' "$rel" "${rel%.sh}.md" >>"${out_dir}/index.md"
done
